// Duplicate detection and normalization
export function normalizeMaterialSpecs(input: {
  name: string;
  size?: string;
  thickness_mm?: number;
  gauge?: string;
  category_id?: string;
}): string {
  const cleanName = input.name.toLowerCase().replace(/[^a-z0-9]/g, '');
  const cleanSize = (input.size ?? '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const thick = input.thickness_mm ? Number(input.thickness_mm).toFixed(2) : '';
  const gauge = (input.gauge ?? '').toUpperCase().replace(/[^0-9G]/g, '');
  return `${input.category_id ?? ''}_${cleanSize || cleanName}_${thick}_${gauge}`;
}

// Bilingual and Alias-aware search filter
export function matchMaterialSearch(item: MaterialItem, term: string): boolean {
  if (!term.trim()) return true;
  const q = term.toLowerCase().trim();

  // 1. Direct name match
  if (item.name.toLowerCase().includes(q)) return true;
  if (item.name_hi.includes(q)) return true;
  if (item.code.toLowerCase().includes(q)) return true;
  if (item.size.toLowerCase().includes(q)) return true;
  if (item.brand?.toLowerCase().includes(q)) return true;
  if (item.gauge?.toLowerCase().includes(q)) return true;

  // 2. Check local aliases
  if (item.local_aliases.some((alias) => alias.toLowerCase().includes(q) || alias.includes(q))) {
    return true;
  }

  // 3. Phonetic matching for common Hindi fabricator terms
  const phonetics: Record<string, string[]> = {
    '1': ['1', 'ek', 'एक'],
    '1.25': ['sawa', 'सवा', '1.25', '1 1/4', '1-1/4'],
    '1.5': ['dedh', 'डेढ़', '1.5', '1 1/2', '1-1/2'],
    '2': ['do', 'दो', '2'],
    '0.75': ['pauna', 'पौना', '3/4', '0.75'],
    'pipe': ['pipe', 'पाइप', 'tube'],
    'angle': ['angle', 'एंगल', 'kona'],
    'sheet': ['sheet', 'चादर', 'chadar'],
    'sariya': ['sariya', 'सरिया', 'bar', 'rod'],
    'patti': ['patti', 'पत्ती', 'flat'],
    'hinge': ['hinge', 'kabja', 'कब्जा'],
  };

  for (const [key, variants] of Object.entries(phonetics)) {
    if (variants.some((v) => q.includes(v))) {
      if (item.name.toLowerCase().includes(key) || item.size.toLowerCase().includes(key)) {
        return true;
      }
    }
  }

  return false;
}
